import { describe, expect, it } from 'vitest'
import { accountRiskError, exceedsRisk, plannedRisk, sizeFromRisk, validRiskPercent } from './risk'
import { cancelEntry, combinedRisk, configureAccount, createTradingState, entryRequestError, modifyStop, observeCandle, requestClose, requestEntry, stopModificationError, type TradingState } from './trading'
import type { Candle } from './history'

const permission = { active: true, playing: false, hasFuture: true }
const risk = (riskPercent = 1) => ({ mode: 'risk' as const, riskPercent })
const bar = (minute: number, open = 1.1, low = open - 0.00001, high = open + 0.00001, close = open): Candle =>
  ({ timestamp: Date.UTC(2024, 0, 9) + minute * 60_000, open, low, high, close })
const tick = (state: TradingState, minute: number, bid = 1.1, ask = 1.1002) => observeCandle(state, bar(minute, bid), bar(minute, ask))
const initial = () => tick(createTradingState(), 0)
const enter = (state = initial(), sizing = risk()) => requestEntry(state, 'buy', sizing, 1.0982, permission)

describe('USD risk calculations', () => {
  it('sizes $1,000 / 20 pips to exactly 5.00 lots and rounds fractional increments down', () => {
    expect(sizeFromRisk(1000, 1.1, 1.098)).toBe(5)
    expect(sizeFromRisk(1000, 1.1, 1.097)).toBe(3.33)
    expect(sizeFromRisk(1000, 1.1, 1.09701)).toBe(3.34)
    expect(sizeFromRisk(1.99, 1.1, 1.098)).toBeNull()
    expect(sizeFromRisk(2, 1.1, 1.098)).toBe(0.01)
  })
  it.each([0, -1, NaN, Infinity, -Infinity])('rejects invalid balances, budgets and prices: %s', (value) => {
    expect(accountRiskError({ referenceBalance: value, maxRiskPercent: 2 })).toContain('balance')
    expect(sizeFromRisk(value, 1.1, 1.098)).toBeNull()
    expect(sizeFromRisk(1000, value, 1.098)).toBeNull()
    expect(sizeFromRisk(1000, 1.1, value)).toBeNull()
    expect(requestEntry(initial(), 'buy', risk(), value, permission).pending).toHaveLength(0)
  })
  it.each([0, -1, 101, NaN, Infinity])('rejects invalid risk percentages %s', (percent) => {
    expect(validRiskPercent(percent)).toBe(false)
    expect(accountRiskError({ referenceBalance: 100_000, maxRiskPercent: percent })).toBeTruthy()
    expect(enter(initial(), risk(percent)).pending).toHaveLength(0)
  })
  it('uses zero gross downside at break-even and in profit for both directions', () => {
    expect(plannedRisk({ direction: 'buy', entryPrice: 1.1, stopPrice: 1.101, lots: 5 })).toBe(0)
    expect(plannedRisk({ direction: 'sell', entryPrice: 1.1, stopPrice: 1.099, lots: 5 })).toBe(0)
    expect(plannedRisk({ direction: 'sell', entryPrice: 1.1, stopPrice: 1.1, lots: 5 })).toBe(0)
    expect(exceedsRisk(2000.01, 2000)).toBe(true)
    expect(exceedsRisk(1e15 + 1, 1e15)).toBe(true)
  })
})

describe('future-opening risk execution and allocations', () => {
  it('queues percentage and USD without lots, sizes a long from actual ask open including spread', () => {
    let state = enter()
    expect(state.pending[0]).toMatchObject({ lots: null, requestedRiskPercent: 1, requestedRiskUsd: 1000 })
    expect(state.positions).toHaveLength(0)
    // The last ask close was 1.1002. The future ask opening gaps to 1.1022.
    state = tick(state, 1, 1.102, 1.1022)
    expect(state.positions[0]).toMatchObject({ entryPrice: 1.1022, lots: 2.5, initialRiskPercent: expect.closeTo(1) })
    expect(state.positions[0].initialRiskUsd).toBeCloseTo(1000)
    expect(observeCandle(state, bar(1), bar(1))).toBe(state)
  })
  it('uses bid open for a short, with the ask stop distance included in USD risk', () => {
    const state = tick(requestEntry(initial(), 'sell', risk(), 1.102, permission), 1)
    expect(state.positions[0]).toMatchObject({ entryPrice: 1.1, lots: 5 })
    expect(state.positions[0].initialRiskUsd).toBeCloseTo(1000)
    expect(plannedRisk({ direction: 'buy', entryPrice: 1.1002, stopPrice: 1.098, lots: 1 })).toBeCloseTo(220)
  })
  it('reserves two independent 1% allocations, then fills within the 2% cap', () => {
    let state = enter(enter())
    expect(combinedRisk(state)).toMatchObject({ reservedUsd: 2000, remainingUsd: 0 })
    state = tick(state, 1)
    expect(state.positions.map((position) => position.lots)).toEqual([5, 5])
    expect(combinedRisk(state).openUsd).toBeCloseTo(2000)
    expect(combinedRisk(state).reservedUsd).toBe(0)
    expect(combinedRisk(state).remainingUsd).toBeCloseTo(0)
  })
  it('rejects an allocation larger than remaining capacity and includes pending closes', () => {
    let state = tick(enter(initial(), risk(1.5)), 1)
    state = requestClose(state, state.positions[0].id, permission)
    expect(entryRequestError(state, risk(1), 1.0982)).toContain('remaining')
    expect(enter(state)).toBe(state)
    expect(combinedRisk(state).openUsd).toBeCloseTo(1500)
  })
  it('enforces manual lots at execution without resizing and gives priority to reserved allocations', () => {
    let state = requestEntry(initial(), 'buy', 6, 1.0982, permission)
    state = enter(state)
    state = tick(state, 1)
    expect(state.rejected[0].lots).toBe(6)
    expect(state.rejected[0].reason).toContain('combined risk cap')
    expect(state.positions[0].lots).toBe(5)
    expect(state.positions[0].mode).toBe('risk')
  })
  it('processes unreserved manual fills in submission order using actual gap risk', () => {
    let state = requestEntry(initial(), 'buy', 3, 1.0982, permission)
    state = requestEntry(state, 'buy', 3, 1.0982, permission)
    state = tick(state, 1, 1.102, 1.1022)
    expect(state.positions).toHaveLength(1)
    expect(state.positions[0]).toMatchObject({ id: '0-1', lots: 3, initialRiskPercent: expect.closeTo(1.2) })
    expect(state.positions[0].initialRiskUsd).toBeCloseTo(1200)
    expect(state.rejected[0].id).toBe('0-2')
  })
  it('releases cancelled and invalid-stop/rejected minimum-size allocations', () => {
    let state = enter()
    state = cancelEntry(state, state.pending[0].id)
    expect(combinedRisk(state).remainingUsd).toBe(2000)
    state = requestEntry(state, 'buy', risk(), 1.101, permission)
    state = tick(state, 1)
    expect(state.rejected[0].reason).toContain('actual entry')
    expect(combinedRisk(state).remainingUsd).toBe(2000)
    state = requestEntry(state, 'buy', risk(0.001), 1.0982, permission)
    state = tick(state, 2)
    expect(state.rejected[1].reason).toContain('below 0.01')
    expect(combinedRisk(state).remainingUsd).toBe(2000)
    expect(state.positions).toHaveLength(0)
  })
  it('keeps reservations pending across missing, invalid and mismatched quotes', () => {
    let state = enter()
    state = observeCandle(state, bar(1))
    state = observeCandle(state, bar(2), bar(3))
    state = observeCandle(state, { ...bar(3), low: NaN }, bar(3))
    expect(combinedRisk(state).reservedUsd).toBe(1000)
    expect(state.positions).toHaveLength(0)
    state = tick(state, 60, 1.102, 1.1022)
    expect(state.positions[0].lots).toBe(2.5)
  })
  it('executes entry and SL in the same candle and releases exposure', () => {
    const state = observeCandle(enter(), bar(1, 1.1, 1.098), bar(1, 1.1002))
    expect(state.closed[0]).toMatchObject({ lots: 5, exitPrice: 1.0982, entryTime: bar(1).timestamp, exitTime: bar(1).timestamp })
    expect(state.closed[0].initialRiskUsd).toBeCloseTo(1000)
    expect(combinedRisk(state).remainingUsd).toBe(2000)
  })
  it('releases a rejected reservation before processing the next submitted entry', () => {
    let state = requestEntry(initial(), 'buy', risk(), 1.101, permission)
    state = enter(state)
    state = tick(state, 1)
    expect(state.rejected[0].id).toBe('0-1')
    expect(state.positions[0]).toMatchObject({ id: '0-2', lots: 5 })
    expect(combinedRisk(state).remainingUsd).toBeCloseTo(1000)
  })
  it('releases exposure only when manual close executes', () => {
    let state = tick(enter(), 1)
    state = requestClose(state, state.positions[0].id, permission)
    expect(combinedRisk(state).openUsd).toBeCloseTo(1000)
    state = tick(state, 2)
    expect(combinedRisk(state).remainingUsd).toBe(2000)
  })
  it('rejects a manual overflow instead of permitting an infinite or unrepresentable risk', () => {
    const state = tick(requestEntry(initial(), 'buy', Number.MAX_VALUE, 1.0982, permission), 1)
    expect(state.positions).toHaveLength(0)
    expect(state.rejected).toHaveLength(1)
  })
})

describe('SL exposure and fixed original entry risk', () => {
  it('reduces exposure for closer, break-even and profit stops, preserving original risk and volume', () => {
    let state = tick(enter(), 1)
    state = tick(state, 2, 1.103, 1.1032)
    const id = state.positions[0].id
    state = modifyStop(state, id, 1.0992, permission)
    expect(combinedRisk(state).openUsd).toBeCloseTo(500)
    state = modifyStop(state, id, 1.1002, permission)
    expect(combinedRisk(state).openUsd).toBe(0)
    state = modifyStop(state, id, 1.101, permission)
    expect(combinedRisk(state).openUsd).toBe(0)
    expect(state.positions[0]).toMatchObject({ lots: 5, initialRiskPercent: expect.closeTo(1), initialRiskUsd: expect.closeTo(1000) })
    expect(state.positions[0].stopModifications).toHaveLength(3)
    expect(state.closed).toHaveLength(0)
  })
  it('reduces short exposure at break-even and into profit while retaining original risk', () => {
    let state = tick(requestEntry(initial(), 'sell', risk(), 1.102, permission), 1)
    state = tick(state, 2, 1.098, 1.0982)
    const id = state.positions[0].id
    state = modifyStop(state, id, 1.1, permission)
    expect(combinedRisk(state).openUsd).toBe(0)
    state = modifyStop(state, id, 1.099, permission)
    expect(combinedRisk(state).openUsd).toBe(0)
    expect(state.positions[0]).toMatchObject({ lots: 5, initialRiskUsd: expect.closeTo(1000), initialRiskPercent: expect.closeTo(1) })
  })
  it('blocks widening beyond capacity, including pending risk reservations', () => {
    let state = tick(enter(), 1)
    state = enter(state)
    expect(stopModificationError(state, state.positions[0], 1.0972, permission)).toContain('combined risk cap')
    expect(modifyStop(state, state.positions[0].id, 1.0972, permission)).toBe(state)
    state = cancelEntry(state, state.pending[0].id)
    state = modifyStop(state, state.positions[0].id, 1.0972, permission)
    expect(combinedRisk(state).openUsd).toBeCloseTo(1500)
    expect(state.positions[0].lots).toBe(5)
  })
  it('locks configuration while active, retains configured inputs on reset, and leaves original risk fixed', () => {
    let state = configureAccount(createTradingState(), { referenceBalance: 50_000, maxRiskPercent: 3 }, { ...permission, active: false })
    state = tick(state, 0)
    state = tick(enter(state), 1)
    expect(state.positions[0]).toMatchObject({ referenceBalance: 50_000, initialRiskUsd: expect.closeTo(500), initialRiskPercent: expect.closeTo(1) })
    expect(configureAccount(state, { referenceBalance: 1, maxRiskPercent: 100 }, permission)).toBe(state)
    const reset = createTradingState(1, state.account)
    expect(reset.account).toEqual({ referenceBalance: 50_000, maxRiskPercent: 3 })
    expect(reset).toMatchObject({ pending: [], positions: [], closed: [], rejected: [] })
  })
})
